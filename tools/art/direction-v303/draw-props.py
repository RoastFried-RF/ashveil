class C:
 def __init__(self,w,h,u=1):
  self.w,self.h,self.u=w,h,u
  self.im=Image.new('RGBA',(w//u,h//u));self.d=ImageDraw.Draw(self.im)
 def color(self,c):return P.get(c,c)
 def p(self,pts,c):self.d.polygon(pts,fill=self.color(c))
 def r(self,x,y,w,h,c):
  if w>0 and h>0:self.d.rectangle((x,y,x+w-1,y+h-1),fill=self.color(c))
 def l(self,pts,c,width=1):self.d.line(pts,fill=self.color(c),width=width)
 def d0(self,x,y,c):self.r(x,y,1,1,c)
 def final(self):return self.im.resize((self.w,self.h),Image.Resampling.NEAREST) if self.u>1 else self.im
 def shadow(self,x,y,w,h=2):
  self.p([(x,y+1),(x+2,y),(x+w-2,y),(x+w,y+1),(x+w-2,y+h),(x+1,y+h)],'shadow')


